// b5-catalogs (P10-R2.E1, B5 arm i) derives an exposure-free twin of a profile
// catalog: the same sources, scopes, products, fields, operators, approval
// routes and budget limits, with the snapshot publications removed, every
// product's snapshot_publication reference dropped, and every budget profile's
// max_*_facts, exposure_profile_version and predicate_footprint (V5-only)
// removed. Under the frozen Gateway a
// grant on such a profile has ExposureGrant.Enabled() == false
// (internal/control/types.go:139), so the query path runs governance,
// execution, artifact publication and receipts without fact accounting
// (internal/gateway/query.go:717). The twin is validated with the production
// catalog loader before it is written, and the tool refuses to write anything
// under config/.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"taskbound.local/agent-data-gateway/internal/catalog"
)

func main() {
	in := flag.String("in", "", "profile catalog to derive from (config/profiles/<name>.catalog.yaml)")
	out := flag.String("out", "", "output path under evaluation/ (default evaluation/config/b5/<name>-no-exposure.catalog.yaml)")
	flag.Parse()
	if *in == "" {
		fmt.Fprintln(os.Stderr, "b5-catalogs: -in is required")
		os.Exit(2)
	}
	if *out == "" {
		base := strings.TrimSuffix(filepath.Base(*in), ".catalog.yaml")
		*out = filepath.Join("evaluation", "config", "b5", base+"-no-exposure.catalog.yaml")
	}
	if rel, err := filepath.Rel("config", *out); err == nil && !strings.HasPrefix(rel, "..") {
		fmt.Fprintln(os.Stderr, "b5-catalogs: refusing to write under config/ (frozen measured path)")
		os.Exit(2)
	}
	raw, err := os.ReadFile(*in)
	if err != nil {
		fatal(err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		fatal(err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		fatal(fmt.Errorf("%s: expected a single mapping document", *in))
	}
	root := doc.Content[0]
	removed := map[string]int{}
	deleteKey(root, "snapshot_publications", removed)
	for _, product := range sequenceItems(mappingValue(root, "products")) {
		deleteKey(product, "snapshot_publication", removed)
	}
	for _, profile := range sequenceItems(mappingValue(root, "budget_profiles")) {
		for _, key := range []string{"max_release_facts", "max_influence_facts", "max_outcome_facts", "exposure_profile_version", "predicate_footprint"} {
			deleteKey(profile, key, removed)
		}
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# B5 arm (i) exposure-free twin of %s, generated by evaluation/cmd/b5-catalogs.\n", *in)
	buf.WriteString("# Same sources, scopes, products, operators, routes and resource budgets; no snapshot\n")
	buf.WriteString("# publications, no product snapshot_publication, no fact limits, no exposure profile.\n")
	buf.WriteString("# Evaluation-owned; never a production or profile-registry catalog.\n")
	encoder := yaml.NewEncoder(&buf)
	encoder.SetIndent(2)
	if err := encoder.Encode(&doc); err != nil {
		fatal(err)
	}
	if err := encoder.Close(); err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
		fatal(err)
	}
	// Validate with the production loader, and check the twin is what it claims.
	twin, err := catalog.Load(*out)
	if err != nil {
		os.Remove(*out)
		fatal(fmt.Errorf("generated twin rejected by catalog.Load: %w", err))
	}
	original, err := catalog.Load(*in)
	if err != nil {
		fatal(err)
	}
	if twin.V4Enabled() {
		os.Remove(*out)
		fatal(fmt.Errorf("twin still V4-enabled"))
	}
	if len(twin.Products) != len(original.Products) || len(twin.ApprovalRoutes) != len(original.ApprovalRoutes) ||
		len(twin.BudgetProfiles) != len(original.BudgetProfiles) {
		os.Remove(*out)
		fatal(fmt.Errorf("twin lost products/routes/profiles: %d/%d/%d vs %d/%d/%d",
			len(twin.Products), len(twin.ApprovalRoutes), len(twin.BudgetProfiles),
			len(original.Products), len(original.ApprovalRoutes), len(original.BudgetProfiles)))
	}
	for _, profile := range twin.BudgetProfiles {
		if profile.ExposureProfileVersion != "" || profile.MaxReleaseFacts != 0 || profile.MaxInfluenceFacts != 0 || profile.MaxOutcomeFacts != 0 {
			os.Remove(*out)
			fatal(fmt.Errorf("budget profile %s still carries exposure limits", profile.Name))
		}
	}
	fmt.Printf("wrote %s: products=%d routes=%d profiles=%d removed=%v v4_enabled=%v\n",
		*out, len(twin.Products), len(twin.ApprovalRoutes), len(twin.BudgetProfiles), removed, twin.V4Enabled())
}

func mappingValue(node *yaml.Node, key string) *yaml.Node {
	if node == nil || node.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			return node.Content[i+1]
		}
	}
	return nil
}

func sequenceItems(node *yaml.Node) []*yaml.Node {
	if node == nil || node.Kind != yaml.SequenceNode {
		return nil
	}
	return node.Content
}

func deleteKey(node *yaml.Node, key string, removed map[string]int) {
	if node == nil || node.Kind != yaml.MappingNode {
		return
	}
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			node.Content = append(node.Content[:i], node.Content[i+2:]...)
			removed[key]++
			return
		}
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "b5-catalogs:", err)
	os.Exit(1)
}
