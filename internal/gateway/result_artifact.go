const artifactRecoveryBatch = 100
const artifactStagingCleanupBatch = 500

func resultIDForQuery(queryID string) string {
	return "res_" + strings.TrimPrefix(queryID, "query_")
}

func artifactObjectKeys(taskID, resultID string) (string, string) {
	// IDs are generated by TaskGate, but hash the task ID as a second line of
	// defense against path injection and to avoid exposing task identifiers to
	// object-store operators through key listings.
	taskHash := sha256.Sum256([]byte(taskID))
	prefix := hex.EncodeToString(taskHash[:16])
	canonical := "results/" + prefix + "/" + resultID + ".parquet.enc"
	staging := "staging/" + prefix + "/" + resultID + "/" + randomID("upload") + ".parquet.enc"
	return staging, canonical
}

// artifactStoredResult converts the connector's canonical layout to the
// caller-visible projection before it becomes the immutable Parquet artifact.
// Semantic identities are reordered with the values so V4 replay remains
// independent of aliases.
func artifactStoredResult(stored storedQueryResult) (storedQueryResult, error) {
	columns, rows, err := publicStoredResult(stored)
	if err != nil {
		return storedQueryResult{}, err
	}
	semantic := append([]string(nil), stored.SemanticColumns...)
	if len(semantic) > 0 && len(stored.ResultOrder) > 0 {
		reordered := make([]string, len(stored.ResultOrder))
		for index, position := range stored.ResultOrder {
			reordered[index] = semantic[position]
		}
		semantic = reordered
	}
	stored.Columns = columns
	stored.Rows = rows
	stored.DisplayColumns = nil
	stored.ResultOrder = nil
	stored.SemanticColumns = semantic
	return stored, nil
}

func artifactColumns(columns []dataconnector.Column) []resultartifact.Column {
	result := make([]resultartifact.Column, len(columns))
	for index, column := range columns {
		result[index] = resultartifact.Column{Name: column.Name, DataTypeOID: column.DataTypeOID}
	}
	return result
}

func (s *Service) stageResultArtifact(ctx context.Context, task control.Task, queryID string,
	stored storedQueryResult) (resultartifact.StagedArtifact, control.ResultArtifact, storedQueryResult, resultartifact.StageMetrics, error) {
	if s.resultArtifacts == nil {
		return resultartifact.StagedArtifact{}, control.ResultArtifact{}, storedQueryResult{}, resultartifact.StageMetrics{}, errors.New("result artifact manager is unavailable")
	}
	publicStored, err := artifactStoredResult(stored)
	if err != nil {
		return resultartifact.StagedArtifact{}, control.ResultArtifact{}, storedQueryResult{}, resultartifact.StageMetrics{}, err
	}
	resultID := resultIDForQuery(queryID)
	stagingKey, objectKey := artifactObjectKeys(task.ID, resultID)
	staged, stageMetrics, err := s.resultArtifacts.StageMeasured(ctx, resultartifact.StageRequest{
		ResultID: resultID, TaskID: task.ID, StagingKey: stagingKey, ObjectKey: objectKey,
		Columns: artifactColumns(publicStored.Columns), Rows: publicStored.Rows,
	})
	if err != nil {
		return resultartifact.StagedArtifact{}, control.ResultArtifact{}, storedQueryResult{}, stageMetrics, err
	}
	metadata := publicStored
	metadata.Rows = nil
	metadataJSON, err := json.Marshal(metadata)
	if err != nil {
		_ = s.resultArtifacts.DeleteStaging(context.WithoutCancel(ctx), staged.StagingKey)
		return resultartifact.StagedArtifact{}, control.ResultArtifact{}, storedQueryResult{}, stageMetrics, err
	}
	schemaJSON, err := json.Marshal(staged.Schema)
	if err != nil {
		_ = s.resultArtifacts.DeleteStaging(context.WithoutCancel(ctx), staged.StagingKey)
		return resultartifact.StagedArtifact{}, control.ResultArtifact{}, storedQueryResult{}, stageMetrics, err
	}
	aclJSON, err := json.Marshal(map[string]any{"principal_id": task.PrincipalID, "task_id": task.ID})
	if err != nil {
		_ = s.resultArtifacts.DeleteStaging(context.WithoutCancel(ctx), staged.StagingKey)
		return resultartifact.StagedArtifact{}, control.ResultArtifact{}, storedQueryResult{}, stageMetrics, err
	}
	now := s.clock().UTC()
	var expiresAt *time.Time
	if s.resultTTL > 0 {
		value := now.Add(s.resultTTL)
		expiresAt = &value
	}
	artifact := control.ResultArtifact{
		ResultID: staged.ResultID, QueryID: queryID, TaskID: task.ID, KeyID: staged.KeyID,
		Format: staged.Format, Encryption: staged.Encryption, StagingKey: staged.StagingKey,
		ObjectKey: staged.ObjectKey, ObjectETag: staged.ETag, ParquetSHA256: staged.ParquetSHA256,
		ObjectSHA256: staged.ObjectSHA256, ParquetSize: staged.ParquetSize, ObjectSize: staged.ObjectSize,
		RowCount: staged.RowCount, ColumnCount: staged.ColumnCount, SchemaJSON: schemaJSON,
		ResultMetadataJSON: metadataJSON, ACLJSON: aclJSON, Status: control.ResultArtifactPending,
		CreatedAt: now, ExpiresAt: expiresAt,
	}
	return staged, artifact, publicStored, stageMetrics, nil
}

func (s *Service) finalizeArtifactQuery(ctx context.Context, task control.Task, requestID string,
	settlement control.BudgetSettlement, stored storedQueryResult, componentMS map[string]float64,
	pipeline *queryPipelineMeasurement) (map[string]any, error) {
	encodingStarted := time.Now()
	if pipeline == nil {
		pipeline = &queryPipelineMeasurement{requestStarted: encodingStarted, prepareFinished: encodingStarted, executeFinished: encodingStarted}
	}
	staged, artifact, publicStored, stageMetrics, err := s.stageResultArtifact(ctx, task, settlement.QueryID, stored)
	componentMS["result_encoding"] = durationMS(time.Since(encodingStarted))
	if publicStored.DiagnosticMS == nil {
		publicStored.DiagnosticMS = make(map[string]float64)
	}
	publicStored.DiagnosticMS["parquet_encode_encrypt"] = durationMS(stageMetrics.EncodeEncrypt)
	publicStored.DiagnosticMS["local_staging_sync"] = durationMS(stageMetrics.Sync)
	publicStored.DiagnosticMS["staging_object_put"] = durationMS(stageMetrics.Put)
	artifactStageFinished := time.Now()
	if err != nil {
		settlement.ErrorCode = resultEncodingFailed
		s.failQueryBudget(ctx, settlement)
		return nil, err
	}
	finalizeCtx, cancel := s.detachedContext(ctx)
	var record control.QueryRecord
	var persistedReceipt control.PersistedQueryReceipt
	var metrics control.FinalizeQueryMetrics
	if settlement.OrdinalExposure != nil || settlement.OrdinalObservationRef != nil {
		record, persistedReceipt, metrics, err = s.store.FinalizeOrdinalQueryArtifactMeasuredWithReceipt(
			finalizeCtx, settlement, artifact, settlement.OrdinalMaterialization, s.terminalReceiptBuilder())
	} else {
		record, persistedReceipt, metrics, err = s.store.FinalizeQueryArtifactMeasuredWithReceipt(
			finalizeCtx, settlement, artifact, s.terminalReceiptBuilder())
	}
	cancel()
	if err != nil {
		// A database Commit error can be ambiguous. Keep the private staging
		// object so a durably committed PENDING intent can still be promoted.
		// Cleanup must never delete staging solely based on wall-clock age.
		settlement.ErrorCode = resultFinalizationFailed
		if errors.Is(err, control.ErrExposureBudgetExhausted) {
			settlement.ErrorCode = string(control.CodeExposureBudgetExhausted)
		}
		if !errors.Is(err, control.ErrCommitOutcomeUnknown) {
			deleteCtx, deleteCancel := s.artifactOperationContext(ctx)
			_ = s.resultArtifacts.DeleteStaging(deleteCtx, staged.StagingKey)
			deleteCancel()
		}
		// Re-read through a fresh connection before attempting a failure
		// settlement. If COMMIT succeeded but its response was lost, the durable
		// COMPLETED record and PENDING artifact are authoritative and can be
		// promoted immediately. A second terminal transition must never be tried.
		recoverCtx, recoverCancel := s.detachedContext(ctx)
		durableRecord, queryErr := s.store.GetQuery(recoverCtx, settlement.QueryID)
		if queryErr == nil && durableRecord.Status == control.QueryCompleted {
			durableArtifact, artifactErr := s.store.GetResultArtifactByQuery(recoverCtx, settlement.QueryID)
			if artifactErr == nil && durableArtifact.Status == control.ResultArtifactPending {
				promotionCtx, promotionCancel := s.artifactOperationContext(ctx)
				durableArtifact, artifactErr = s.promoteResultArtifact(promotionCtx, durableArtifact, durableRecord.Actor)
				promotionCancel()
			}
			if artifactErr == nil && durableArtifact.Status == control.ResultArtifactAvailable {
				durableStored, _, metadataErr := decodeArtifactMetadata(durableArtifact)
				durableReceipt, receiptErr := s.queryReceipt(recoverCtx, durableRecord)
				if metadataErr != nil {
					recoverCancel()
					return nil, metadataErr
				}
				if receiptErr != nil {
					recoverCancel()
					return nil, receiptErr
				}
				response := s.artifactQueryResponse(recoverCtx, durableArtifact, durableStored, durableRecord, requestID, durableReceipt)
				recoverCancel()
				return response, nil
			}
			if artifactErr != nil {
				s.artifactRecoveryFailures.Store(1)
			}
			recoverCancel()
			return nil, &mcp.ToolError{Code: apierr.CodeConflict, Message: "结果已结算，规范 Parquet 正在恢复；请使用相同 request_id 重试"}
		}
		recoverCancel()
		if queryErr == nil && durableRecord.Status != control.QueryReserved {
			return nil, err
		}
		s.failQueryBudget(ctx, settlement)
		return nil, err
	}
	componentMS["settle_persist"] = durationMS(metrics.SettlementStore)
	componentMS["receipt_signing"] = durationMS(metrics.ReceiptSigning)
	if settlement.Exposure != nil || settlement.OrdinalExposure != nil || settlement.OrdinalObservationRef != nil {
		componentMS["exposure_reservation_lock"] = durationMS(metrics.ExposureReservationLock)
		componentMS["exposure_ledger_lock"] = durationMS(metrics.ExposureLedgerLock)
		componentMS["exposure_fact_store"] = durationMS(metrics.ExposureFactStore)
	}
	publicStored.DiagnosticMS["receipt_signing"] = durationMS(metrics.ReceiptSigning)
	publicStored.DiagnosticMS["exposure_reservation_lock"] = durationMS(metrics.ExposureReservationLock)
	publicStored.DiagnosticMS["exposure_ledger_lock"] = durationMS(metrics.ExposureLedgerLock)
	publicStored.DiagnosticMS["exposure_fact_store"] = durationMS(metrics.ExposureFactStore)
	publicStored.DiagnosticMS["outcome_radix_load"] = durationMS(metrics.OutcomeRadix.LoadDuration)
	publicStored.DiagnosticMS["outcome_radix_difference_union"] = durationMS(metrics.OutcomeRadix.DifferenceUnionDuration)
	publicStored.DiagnosticMS["outcome_radix_persist"] = durationMS(metrics.OutcomeRadix.PersistDuration)
	settlementFinished := time.Now()
	// The Control transaction is now terminal. A promotion error must never
	// attempt to settle or refund the query a second time; startup/idempotent
	// replay will resume this deterministic copy.
	promoteCtx, promoteCancel := s.artifactOperationContext(ctx)
	var promoteMetrics resultartifact.PromoteMetrics
	var markAvailableDuration time.Duration
	artifact, promoteMetrics, markAvailableDuration, err = s.promoteResultArtifactMeasured(promoteCtx, artifact, record.Actor)
	promoteCancel()
	if err != nil {
		// Accounting is already terminal and the PENDING intent is durable. Keep
		// readiness closed until the full reconciliation pass proves recovery.
		s.artifactRecoveryFailures.Store(1)
		return nil, &mcp.ToolError{Code: apierr.CodeConflict, Message: "结果已结算，规范 Parquet 正在恢复；请使用相同 request_id 重试"}
	}
	publicStored.DiagnosticMS["canonical_object_stat"] = durationMS(promoteMetrics.Stat)
	publicStored.DiagnosticMS["canonical_object_copy"] = durationMS(promoteMetrics.Copy)
	publicStored.DiagnosticMS["canonical_object_verify"] = durationMS(promoteMetrics.Verify)
	publicStored.DiagnosticMS["canonical_object_hash_verify"] = durationMS(promoteMetrics.HashVerify)
	publicStored.DiagnosticMS["staging_object_delete"] = durationMS(promoteMetrics.DeleteStaging)
	publicStored.DiagnosticMS["mark_available"] = durationMS(markAvailableDuration)
	publicationFinished := time.Now()
	receipt, err := decodeReceiptJSON(persistedReceipt.ReceiptJSON)
	if err != nil {
		return nil, err
	}
	response := s.artifactQueryResponse(ctx, artifact, publicStored, record, requestID, receipt)
	if metrics.OutcomeRadix.CandidateCardinality > 0 {
		response["outcome_radix"] = metrics.OutcomeRadix
	}
	finalizePipelineResponse(response, publicStored, pipeline, artifactStageFinished, settlementFinished, publicationFinished)
	return response, nil
}

func (s *Service) artifactQueryResponse(ctx context.Context, artifact control.ResultArtifact,
	stored storedQueryResult, record control.QueryRecord, requestID string, receipt map[string]any) map[string]any {
	result := publicArtifact(artifact, stored)
	result["request_id"] = requestID
	result["status"] = record.Status
	result["receipt"] = receipt
	if charge, exposureErr := s.store.GetExposureCharge(ctx, record.ID); exposureErr == nil {
		result["exposure"] = charge
		if ledger, ledgerErr := s.store.GetExposureLedger(ctx, record.TaskID); ledgerErr == nil {
			result["exposure_budget"] = ledger
		}
	}
	return result
}

func stagedFromControl(artifact control.ResultArtifact) resultartifact.StagedArtifact {
	return resultartifact.StagedArtifact{
		ResultID: artifact.ResultID, TaskID: artifact.TaskID, StagingKey: artifact.StagingKey,
		ObjectKey: artifact.ObjectKey, KeyID: artifact.KeyID, Format: artifact.Format,
		Encryption: artifact.Encryption, ParquetSHA256: artifact.ParquetSHA256,
		ObjectSHA256: artifact.ObjectSHA256, ParquetSize: artifact.ParquetSize,
		ObjectSize: artifact.ObjectSize, RowCount: artifact.RowCount, ColumnCount: artifact.ColumnCount,
		ETag: artifact.ObjectETag,
	}
}

